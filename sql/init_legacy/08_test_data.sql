DROP TABLE IF EXISTS rel_brand_factory CASCADE;

CREATE TABLE rel_brand_factory (
    rel_id SERIAL PRIMARY KEY,
    brand_id INT NOT NULL,
    factory_id INT NOT NULL,
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_brand_factory UNIQUE (brand_id, factory_id)
);

CREATE INDEX idx_rel_brand ON rel_brand_factory(brand_id);
CREATE INDEX idx_rel_factory ON rel_brand_factory(factory_id);

